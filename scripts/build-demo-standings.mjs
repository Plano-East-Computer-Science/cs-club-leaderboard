// Spread a total over dated awards, oldest first, in chunks a club would really give.
function awards(total, from, to) {
  const rows = [];
  let left = total;
  while (left > 0) {
    const chunk = Math.min(left, [10, 10, 10, 15, 20, 25, 30][Math.floor(rand() * 7)]);
    const t = new Date(from + rand() * (to - from));
    rows.push([chunk, t.toISOString().slice(0, 19).replace('T', ' ')]);
    left -= chunk;
  }
  return rows.sort((a, b) => a[1].localeCompare(b[1]));
}

