/**
 * Generates worker/seed-data-arena.sql: two small synthetic challenges for the
 * data arena (C12). The data is invented here from a seeded random generator,
 * so there is nothing to license. Rerun after editing the recipes:
 *   node scripts/make-data-seed.mjs
 * Apply (local only):
 *   npx wrangler d1 execute cs-club --local --persist-to .wrangler/state --file worker/seed-data-arena.sql
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'worker', 'seed-data-arena.sql');

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const normal = (r) => Math.sqrt(-2 * Math.log(1 - r())) * Math.cos(2 * Math.PI * r());
const round = (x, d = 1) => Math.round(x * 10 ** d) / 10 ** d;
const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x));
const csv = (head, rows) => [head.join(','), ...rows.map((r) => r.join(','))].join('\n') + '\n';

/** Builds train/test/answers from a row maker. Ids are shuffled so row order leaks nothing. */
function build(seed, n, nTest, make, features, target) {
  const r = rng(seed);
  const all = Array.from({ length: n + nTest }, (_, i) => ({ id: i + 1, ...make(r) }));
  for (let i = all.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    [all[i], all[j]] = [all[j], all[i]];
  }
  const train = all.slice(0, n);
  const test = all.slice(n).sort((a, b) => a.id - b.id);
  train.sort((a, b) => a.id - b.id);
  return {
    train: csv(['id', ...features, target], train.map((x) => [x.id, ...features.map((f) => x[f]), x[target]])),
    test: csv(['id', ...features], test.map((x) => [x.id, ...features.map((f) => x[f])])),
    answers: csv(['id', target], test.map((x) => [x.id, x[target]])),
    rows: nTest,
  };
}

// 1. Classification: did the student pass Monday's quiz?
const quiz = build(
  1201, 700, 250,
  (r) => {
    const sleep = round(clamp(6.8 + normal(r) * 1.3, 3, 10));
    const study = Math.round(clamp(35 + normal(r) * 25, 0, 150));
    const screen = round(clamp(3.5 + normal(r) * 1.8, 0, 10));
    const snack = r() < 0.5 ? 1 : 0;
    const grade = 9 + Math.floor(r() * 4);
    const z = 0.55 * (sleep - 7) + 0.035 * (study - 35) - 0.3 * (screen - 3.5) + 0.4 * snack + 0.1 * (grade - 10) + normal(r) * 0.9 + 0.2;
    return { sleep_hours: sleep, study_minutes: study, screen_hours: screen, ate_breakfast: snack, grade_level: grade, passed: z > 0 ? 1 : 0 };
  },
  ['sleep_hours', 'study_minutes', 'screen_hours', 'ate_breakfast', 'grade_level'],
  'passed'
);

// 2. Regression: how many minutes does the bus ride take?
const bus = build(
  3407, 650, 220,
  (r) => {
    const miles = round(clamp(4 + Math.abs(normal(r)) * 3.2, 0.5, 18));
    const stops = Math.round(clamp(miles * 1.4 + normal(r) * 2, 1, 30));
    const rain = r() < 0.25 ? 1 : 0;
    const hour = 6 + Math.floor(r() * 3); // 6, 7 or 8 am
    const rush = hour === 7 ? 1 : 0;
    const minutes = 5 + 2.4 * miles + 0.9 * stops + 4.5 * rain + 3.2 * rush + 0.12 * miles * stops * (rain ? 1 : 0.5) + normal(r) * 2.2;
    return { distance_miles: miles, stops, raining: rain, start_hour: hour, minutes: round(Math.max(4, minutes)) };
  },
  ['distance_miles', 'stops', 'raining', 'start_hour'],
  'minutes'
);

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const insert = (c) => `INSERT INTO data_challenges (title, summary, metric, id_col, target_col, train_csv, test_csv, answers_csv, rows, created_by)
SELECT ${q(c.title)}, ${q(c.summary)}, ${q(c.metric)}, 'id', ${q(c.target)}, ${q(c.d.train)}, ${q(c.d.test)}, ${q(c.d.answers)}, ${c.d.rows}, 'seed'
WHERE NOT EXISTS (SELECT 1 FROM data_challenges WHERE title = ${q(c.title)});
`;

const sql = [
  '-- Generated by scripts/make-data-seed.mjs. Synthetic data, invented for the club.',
  insert({
    title: 'Quiz night',
    metric: 'accuracy',
    target: 'passed',
    summary:
      'Did the student pass Monday\'s quiz? Each row is one student: hours slept, minutes studied, screen hours, whether they ate breakfast and their grade level.\n\n' +
      'train.csv has the answer in the passed column (1 = passed). test.csv does not. Predict passed for every id in test.csv and submit a file with two columns, id and passed. ' +
      'Your score is accuracy, the share you got right. Guessing the most common answer is the number to beat.',
    d: quiz,
  }),
  insert({
    title: 'Bus ride',
    metric: 'rmse',
    target: 'minutes',
    summary:
      'How long does the morning bus ride take? Each row is one route: distance in miles, number of stops, whether it was raining and the hour it started.\n\n' +
      'train.csv has the answer in the minutes column. test.csv does not. Predict minutes for every id in test.csv and submit a file with two columns, id and minutes. ' +
      'Your score is RMSE, the typical size of your mistakes in minutes, so lower is better. Always predicting the average is the number to beat.',
    d: bus,
  }),
].join('\n');

fs.writeFileSync(out, sql);
for (const [n, d] of [['quiz', quiz], ['bus', bus]]) console.log(`${n}: train ${d.train.length} B, test ${d.test.length} B, answers ${d.answers.length} B`);
